const STR = { es: ES, en: EN };
let lang = 'es';

export function setLang(l) { lang = STR[l] ? l : 'es'; return lang; }
export function getLang() { return lang; }

/** Texto en el idioma activo, con `{var}` reemplazadas. */
export function t(key, vars) {
  let s = STR[lang][key] ?? ES[key];
  if (s === undefined) return key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(String(vars[k]));
  return s;
}

/** Un texto con variantes por idioma ({es, en}) o un string pelado. */
export function tx(v) {
  if (v && typeof v === 'object') return v[lang] ?? v.es ?? '';
  return v ?? '';
}

/** mm:ss a partir de segundos. */
export function fmtTime(sec) {
  const m = Math.floor(sec / 60), s = Math.floor(sec % 60);
  return m + ':' + String(s).padStart(2, '0');
}

/** Nombre corto y legible de un código de tecla (`KeyA` → `A`, `Mouse0` → `clic`). */
export function keyName(code) {
  if (!code) return '—';
  if (code === 'Mouse0') return lang === 'es' ? 'clic' : 'click';
  if (code === 'Mouse1') return lang === 'es' ? 'rueda' : 'wheel';
  if (code === 'Mouse2') return lang === 'es' ? 'clic der.' : 'right click';
  if (code.startsWith('Key')) return code.slice(3);
  if (code.startsWith('Digit')) return code.slice(5);
  if (code.startsWith('Arrow')) return { Up: '↑', Down: '↓', Left: '←', Right: '→' }[code.slice(5)] || code;
  const map = { Space: lang === 'es' ? 'espacio' : 'space', ShiftLeft: 'shift', ShiftRight: 'shift der.', ControlLeft: 'ctrl', ControlRight: 'ctrl der.', AltLeft: 'alt', AltRight: 'alt gr', Escape: 'esc', Enter: 'enter', Tab: 'tab', Backspace: 'retroceso', CapsLock: 'bloq mayús' };
  return map[code] || code.toLowerCase();
}

/**
 * Traduce lo estático del DOM: cada elemento con `data-t="clave"` recibe el
 * texto; con `data-t-html` va como HTML (para negritas de la leyenda).
 */
export function applyDom(root = document) {
  for (const el of root.querySelectorAll('[data-t]')) el.textContent = t(el.dataset.t);
  for (const el of root.querySelectorAll('[data-t-html]')) el.innerHTML = t(el.dataset.tHtml);
}
